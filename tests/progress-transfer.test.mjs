import test from "node:test";
import assert from "node:assert/strict";
import {
  exportProgressCode,
  importProgressCode,
  normalizeProgress,
  mergeProgress,
} from "../dist/progress-transfer.js";
import { lessons } from "../dist/lessons.js";
import { calculate, math } from "../dist/math.js";
import { packProgress, unpackProgress } from "../dist/progress-codec.js";
const p = {
  index: 2,
  stage: "practice",
  solved: [0, 1],
  answers: { 0: "−3", 1: "1 1/2" },
  hints: [2],
  reveals: [],
};
const state = {
  version: 1,
  progress: { "integers-1": p },
  lesson: "integers-1",
};
test("progress codes round trip Unicode answers and lesson position", () => {
  const code = exportProgressCode(state);
  assert.deepEqual(importProgressCode(code), state);
  assert.deepEqual(
    importProgressCode(code.slice(0, 20) + "\n" + code.slice(20)),
    state,
  );
});

test("previous valid NUMI1 codes are rejected while NUMI2 codes still round trip", () => {
  // Fixed fixture generated by the original JSON exporter, including a Unicode minus.
  const legacy =
    "NUMI1.eyJ2ZXJzaW9uIjoxLCJwcm9ncmVzcyI6eyJpbnRlZ2Vycy0xIjp7ImluZGV4IjoyLCJzdGFnZSI6InByYWN0aWNlIiwic29sdmVkIjpbMCwxXSwiYW5zd2VycyI6eyIwIjoi4oiSMyIsIjEiOiIxIDEvMiJ9LCJoaW50cyI6WzJdLCJyZXZlYWxzIjpbXX19LCJsZXNzb24iOiJpbnRlZ2Vycy0xIn0.dab230fa";
  assert.throws(() => importProgressCode(legacy), /no longer supported/);
  const compact = exportProgressCode(state);
  assert.match(compact, /^NUMI2\./);
  assert.ok(compact.length < legacy.length * 0.4);
  assert.deepEqual(importProgressCode(compact), state);
});

test("compact codes preserve all lesson data while avoiding empty-field overhead", () => {
  for (const completed of [false, true]) {
    const progress = Object.fromEntries(
      lessons.map((l) => [
        l.id,
        {
          index: completed ? l.problems.length - 1 : 0,
          stage: completed ? "practice" : "example",
          solved: completed ? l.problems.map((_, i) => i).reverse() : [],
          answers: completed
            ? Object.fromEntries(l.problems.map((p, i) => [i, p.answer]))
            : {},
          hints: completed ? [0] : [],
          reveals: completed ? [0, 1] : [],
          failedChecks: completed ? { 0: 1, 1: 2 } : {},
        },
      ]),
    );
    const saved = {
      version: 1,
      lesson: completed ? "factors-2" : null,
      progress,
    };
    const code = exportProgressCode(saved);
    assert.deepEqual(importProgressCode(code), saved);
    const originalSize =
      Math.ceil(
        (new TextEncoder().encode(JSON.stringify(saved)).length * 4) / 3,
      ) + 15;
    assert.ok(
      code.length < originalSize * 0.4,
      `${code.length} versus ${originalSize}`,
    );
  }
});

test("compact binary parsing rejects truncation, excessive counts, duplicates, and trailing data", () => {
  const bytes = packProgress(normalizeProgress(state));
  for (let length = 0; length < bytes.length; length++)
    assert.throws(() => unpackProgress(bytes.slice(0, length)));
  for (const malformed of [
    [...bytes, 0],
    [8, 1, 8, 128, 1], // Unknown flags.
    [99], // Unknown numeric lesson ID.
    [0, 1, 255], // Invalid UTF-8.
    [8, 2, 8, 0, 8, 0], // Duplicate lesson entries.
    [0, 0, 255, 255, 255, 255, 127], // Out-of-range collection length.
  ])
    assert.throws(() => unpackProgress(Uint8Array.from(malformed)));
});

test("new lesson IDs can use strings without changing the frozen format dictionary", () => {
  const future = {
    version: 1,
    lesson: "future-lesson",
    progress: {
      "future-lesson": {
        ...p,
        answers: { 0: "0.75", 1: "\u22123", 2: "1 1/2" },
        failedChecks: {},
      },
    },
  };
  assert.deepEqual(unpackProgress(packProgress(future)), future);
});
test("corrupted, incomplete, and oversized codes are rejected", () => {
  const code = exportProgressCode(state),
    corrupt = code.slice(0, -1) + (code.endsWith("0") ? "1" : "0");
  for (const input of [
    corrupt,
    code.slice(0, -10),
    "wrong",
    "NUMI1." + "x".repeat(200001),
  ])
    assert.throws(() => importProgressCode(input));
  assert.throws(() =>
    normalizeProgress({ version: 2, progress: state.progress }),
  );
  assert.throws(() =>
    normalizeProgress({
      version: 1,
      progress: { "integers-1": { ...p, solved: [99] } },
    }),
  );
});
test("imports keep already solved problems and support previous JSON files", () => {
  const incoming = normalizeProgress({
    ...state,
    progress: {
      "integers-1": {
        ...p,
        solved: [1, 2],
        hints: undefined,
        reveals: undefined,
      },
    },
  });
  const merged = mergeProgress(state.progress, incoming.progress);
  assert.deepEqual(merged["integers-1"].solved, [0, 1, 2]);
  assert.equal(merged["integers-1"].answers[0], "−3");
  assert.deepEqual(state.progress["integers-1"].solved, [0, 1]);
});
test("every rendered worked-equation line is mathematically equivalent", () => {
  for (const example of lessons.flatMap((l) => [
    l.example,
    ...(l.moreExamples || []),
  ])) {
    assert.ok(
      Math.abs(calculate(example.expr) - calculate(example.answer)) < 1e-10,
      example.expr,
    );
    for (const step of example.steps)
      for (const line of step.lines) {
        const first = calculate(line[0]);
        for (const term of line) {
          assert.ok(Math.abs(calculate(term) - first) < 1e-10, line.join("="));
          assert.match(math(term), /<math /);
        }
      }
  }
});

test("help unlock counts round trip, validate, and merge without relocking", () => {
  const withAttempts = {
    ...state,
    progress: { "integers-1": { ...p, failedChecks: { 0: 1, 2: 2 } } },
  };
  assert.deepEqual(
    importProgressCode(exportProgressCode(withAttempts)),
    withAttempts,
  );
  const incoming = { "integers-1": { ...p, failedChecks: { 0: 2, 2: 1 } } };
  const merged = mergeProgress(withAttempts.progress, incoming);
  assert.deepEqual(merged["integers-1"].failedChecks, { 0: 2, 2: 2 });
  const legacy = mergeProgress(withAttempts.progress, state.progress);
  assert.deepEqual(legacy["integers-1"].failedChecks, { 0: 1, 2: 2 });
  for (const failedChecks of [
    [],
    null,
    { 0: -1 },
    { 0: 3 },
    { 0: 0.5 },
    { 99: 1 },
    { other: 1 },
  ])
    assert.throws(() =>
      normalizeProgress({
        ...state,
        progress: { "integers-1": { ...p, failedChecks } },
      }),
    );
});
